package controlplane

import (
	"strings"
	"testing"
)

func TestPostgresSQLRewritesPlaceholdersOutsideStrings(t *testing.T) {
	query := `SELECT j.id FROM jobs j WHERE j.state IN ('queued','running') AND j.title = ? AND j.prompt LIKE ?`
	rewritten := postgresSQL(query)
	if !strings.Contains(rewritten, "$1") || !strings.Contains(rewritten, "$2") {
		t.Fatalf("placeholders not numbered: %s", rewritten)
	}
	if strings.Contains(rewritten, "?") {
		t.Fatalf("unrewritten placeholder remains: %s", rewritten)
	}
	// Quoted text is never mangled.
	if !strings.Contains(rewritten, `'queued','running'`) {
		t.Fatalf("string literal damaged: %s", rewritten)
	}
}

func TestPostgresSQLRewritesJSONHelpers(t *testing.T) {
	query := `SELECT COALESCE(json_extract(metadata,'$.project'),'') FROM job_metadata WHERE json_valid(task) AND json_extract(task,'$.source_url')=?`
	rewritten := postgresSQL(query)
	if !strings.Contains(rewritten, "tf_json_extract(metadata,'$.project')") {
		t.Fatalf("json_extract not remapped: %s", rewritten)
	}
	if !strings.Contains(rewritten, "tf_json_valid(task)") {
		t.Fatalf("json_valid not remapped: %s", rewritten)
	}
	if strings.Contains(rewritten, "tf_json_extract(task,'$.source_url')=?") {
		t.Fatalf("placeholder not numbered: %s", rewritten)
	}
}

func TestPostgresSQLRewritesRowid(t *testing.T) {
	rewritten := postgresSQL(`SELECT id FROM runs WHERE job_id=? ORDER BY rowid DESC LIMIT 1`)
	if !strings.Contains(rewritten, "ORDER BY rowseq DESC LIMIT 1") {
		t.Fatalf("rowid not remapped: %s", rewritten)
	}
}

func TestPostgresDDLPreservesTablesAndDropsPragmas(t *testing.T) {
	ddl := postgresDDL(baseSchema + workflowSchema + artifactSchema + reviewSchema + jobMetadataSchema + planeSchema + autoMergeSchema + ticketSchema)
	for _, table := range []string{"jobs", "runs", "workers", "tickets", "settings", "job_metadata", "workflow_jobs", "plane_intake", "automerge_jobs"} {
		if !strings.Contains(ddl, "CREATE TABLE IF NOT EXISTS "+table) {
			t.Fatalf("table %s missing from translated DDL", table)
		}
	}
	if strings.Contains(strings.ToUpper(ddl), "PRAGMA") {
		t.Fatalf("PRAGMA survived translation: %s", ddl[:300])
	}
	if strings.Contains(ddl, "AUTOINCREMENT") {
		t.Fatal("AUTOINCREMENT survived translation")
	}
	// Identity keys land inside the tables that need insertion order.
	for _, table := range rowseqTables {
		if !strings.Contains(ddl, "rowseq BIGINT GENERATED BY DEFAULT AS IDENTITY,") {
			t.Fatalf("rowseq missing for %s", table)
		}
		break
	}
}

func TestPostgresDialectDetection(t *testing.T) {
	for url, want := range map[string]bool{
		"postgres://u:p@h/db":      true,
		"postgresql://u:p@h/db":    true,
		"~/.machinist/server/m.db": false,
		"/var/lib/machinist/db":    false,
		"postGRES://u:p@h/db":      false, // case-sensitive by contract
		"postgres:/not-a-url":      false,
	} {
		if got := postgresDialect(url); got != want {
			t.Fatalf("postgresDialect(%q) = %v, want %v", url, got, want)
		}
	}
}
